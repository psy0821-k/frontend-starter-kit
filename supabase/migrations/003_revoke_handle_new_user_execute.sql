-- ============================================================
-- 003. handle_new_user() 직접 호출 차단
-- ============================================================
-- handle_new_user()는 auth.users INSERT 트리거 전용이며, REST RPC
-- (/rest/v1/rpc/handle_new_user)로 익명/로그인 사용자가 직접 호출할 이유가
-- 없다. SECURITY DEFINER 함수가 트리거 밖에서 직접 실행 가능하면 정의자
-- 권한으로 임의 profiles 행을 삽입하는 통로가 될 수 있어 EXECUTE 권한을
-- 회수한다.
--
-- 참고: 로컬 마이그레이션 파일이 누락되어 있던 것을 사후 복원한 것이다.
-- 복원 시점(2026-08-10) 재확인 결과 anon/authenticated에 EXECUTE 권한이
-- 여전히 남아있는 것으로 확인되어(원인 불명 — 최초 적용 실패 또는 이후
-- 재부여 추정), 이 마이그레이션이 재적용되며 함께 바로잡는다.
-- ============================================================

revoke execute on function public.handle_new_user() from anon, authenticated;
